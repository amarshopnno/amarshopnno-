-- Amar Shop Supabase database setup
-- Run this whole script in Supabase Dashboard > SQL Editor > New query.
-- Public visitors can READ products. Only the specific user IDs listed in admin_users can INSERT/UPDATE/DELETE.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 160),
  price numeric(12,2) not null check (price >= 0),
  category text not null default 'অন্যান্য',
  emoji text not null default '🛍️',
  image_url text not null default '',
  description text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;
alter table public.admin_users enable row level security;

-- Clear only policies with these exact names, then recreate them safely.
drop policy if exists "products_public_read" on public.products;
drop policy if exists "products_admin_insert" on public.products;
drop policy if exists "products_admin_update" on public.products;
drop policy if exists "products_admin_delete" on public.products;
drop policy if exists "admin_users_read_self" on public.admin_users;

create policy "products_public_read"
  on public.products for select
  to anon, authenticated
  using (true);

create policy "products_admin_insert"
  on public.products for insert
  to authenticated
  with check (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())));

create policy "products_admin_update"
  on public.products for update
  to authenticated
  using (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())))
  with check (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())));

create policy "products_admin_delete"
  on public.products for delete
  to authenticated
  using (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())));

create policy "admin_users_read_self"
  on public.admin_users for select
  to authenticated
  using (user_id = (select auth.uid()));

-- Grant only the table actions needed by the website; RLS still applies.
grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;
grant select on public.admin_users to authenticated;
grant usage, select on sequence public.products_id_seq to authenticated;

